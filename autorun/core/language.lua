function Language.current()
    return current
end

function Language.set(code)
    if code == "en" or code == "vi" then
        current = code
    end
end

function Language.translate(text)
    if current ~= "vi" or type(text) ~= "string" then
        return text
    end
    return VIETNAMESE[text] or text
end

function Language.format(pattern, ...)
    if current ~= "vi" then
        return string.format(pattern, ...)
    end
    local count = select("#", ...)
    local arguments = { ... }
    for index = 1, count do
        if type(arguments[index]) == "string" then
            arguments[index] = Language.translate(arguments[index])
        end
    end
    return string.format(Language.translate(pattern), table.unpack(arguments, 1, count))
end

-- imgui labels: only the part before "##" is visible; "##ev3"-style ids are stored with the id prefix.
function Language.translate_label(text)
    if current ~= "vi" or type(text) ~= "string" then
        return text
    end
    local translated = VIETNAMESE[text]
    if translated then
        return translated
    end
    local visible, identifier = text:match("^(.-)(##.*)$")
    if not visible then
        return text
    end
    translated = VIETNAMESE[visible]
    if translated then
        return translated .. identifier
    end
    local identifier_prefix = identifier:match("^(##%a+)")
    if identifier_prefix then
        translated = VIETNAMESE[visible .. identifier_prefix]
        if translated then
            return translated .. identifier:sub(#identifier_prefix + 1)
        end
    end
    return text
end

function Language.translate_list(list)
    if current ~= "vi" then
        return list
    end
    local translated = {}
    for index, text in ipairs(list) do
        translated[index] = Language.translate_label(text)
    end
    return translated
end

return Language
